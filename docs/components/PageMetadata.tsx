import { parse } from 'date-fns';

import { buildAuthors } from '@monetr/docs/components/hooks/useDocPages';
import realUrl from '@monetr/docs/components/utils/realUrl';

import { Head, usePage } from '@rspress/core/runtime';
import { Fragment } from 'react/jsx-runtime';

// This has to render after the rspress layout in theme/index.tsx so that anything here wins over the tags rspress adds
// itself.
export default function PageMetadata(): React.JSX.Element {
  const { page } = usePage();
  const { frontmatter } = page;
  const url = realUrl(page.routePath);

  let type = 'website';
  let published: Array<string> = [];
  let modified: Array<string> = [];
  if (frontmatter?.date) {
    type = 'article';
    published = [parse(frontmatter?.date as string, 'yyyy/MM/dd', new Date()).toISOString()];
    modified = page.lastUpdatedTime ? [new Date(page.lastUpdatedTime).toISOString()] : [];
  }
  const authors = buildAuthors(page);

  // Pages without an ogImage in their frontmatter get one generated by the og images plugin at build time.
  const ogImage = (frontmatter?.ogImage as string | undefined) ?? (page.ogImage as string | undefined);

  // rspress only uses the frontmatter title on doc pages, custom pages (home, pricing, blog) always just get "monetr".
  // So for custom pages we use the frontmatter title as is, the frontmatter should include monetr in it.
  const customTitle = page.pageType === 'custom' && frontmatter?.title ? (frontmatter.title as string) : null;

  return (
    <Head>
      {/* canonical */}
      <link href={url} rel='canonical' />
      {customTitle ? (
        <Fragment>
          <title>{customTitle}</title>
          <meta content={customTitle} property='og:title' />
        </Fragment>
      ) : null}
      {/* opengraph things */}
      <meta content={type} property='og:type' />
      <meta content={url} property='og:url' />
      <meta content='monetr' property='og:site_name' />
      <meta content='en_US' property='og:locale' />
      <meta content={page.title} name='title' />
      {ogImage ? <meta content={realUrl(ogImage)} property='og:image' /> : null}
      {/* misc? */}
      <meta content={page.lang} httpEquiv='Content-Language' />
      {/* Article stuff */}
      {authors.map(author => (
        <meta content={author.name} key={author.name} property='article:author' />
      ))}
      {published.map(timestamp => (
        <meta content={timestamp} key={timestamp} property='article:published_time' />
      ))}
      {modified.map(timestamp => (
        <meta content={timestamp} key={timestamp} property='article:modified_time' />
      ))}
      {/* Twitter bullshit, title and description fall back to the og tags */}
      <meta content='monetr.app' property='twitter:domain' />
      <meta content={url} property='twitter:url' />
      {ogImage ? (
        <Fragment>
          <meta content='summary_large_image' name='twitter:card' />
          <meta content={realUrl(ogImage)} name='twitter:image' />
        </Fragment>
      ) : (
        <meta content='summary' name='twitter:card' />
      )}
    </Head>
  );
}

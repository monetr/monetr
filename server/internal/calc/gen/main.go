// Command gen writes the lookup tables that the fixed size assembly
// implementations of the fast Fourier transform depend on. All three of them,
// AVX512 and both 256 bit variants, read the same two tables.
//
// Two tables come out of this:
//
//   - fourierTwiddles<size>, the complex roots of unity for the radix-4 passes.
//     Each pass contributes h copies of W(2h)^j followed by h copies of W(4h)^j,
//     and the passes are packed smallest first so the inner loop only ever reads
//     forward.
//
//   - fourierScatter<size>, the byte offset each group of four outputs from the
//     first pass belongs at. This is the bit reversal permutation, converted
//     ahead of time into the exact offsets the store instructions want.
//
// The size is part of the symbol names so that regenerating at a different size
// without updating the assembly is a link error.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"math"
	"math/bits"
	"os"
	"path/filepath"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	size := flag.Int("size", 4096, "number of points the transform is built for, must be a power of four")
	output := flag.String("output", "fourier_twiddles_amd64.s", "path of the assembly file to write")
	flag.Parse()

	// The assembly runs everything as radix-4, so the size has to be a power of
	// four rather than merely a power of two. It also has to be at least 16,
	// because the first pass reads four points at a time out of each quarter of
	// the input. 4096 is 4^6: one radix-4 first pass and five more after it.
	if *size < 16 || *size&(*size-1) != 0 || bits.TrailingZeros(uint(*size))%2 != 0 {
		log.Fatalf("size must be a power of four that is at least 16, got %d", *size)
	}

	file, err := os.Create(*output)
	if err != nil {
		log.Fatalf("could not create %s: %v", *output, err)
	}
	defer file.Close()

	buffer := bufio.NewWriterSize(file, 1<<20)
	twiddleBytes := writeTwiddles(buffer, *size)
	scatterBytes := writeScatter(buffer, *size)
	if err := buffer.Flush(); err != nil {
		log.Fatalf("could not write %s: %v", *output, err)
	}

	log.Printf(
		"wrote %s for %d points, %d bytes of twiddle factors and %d bytes of scatter offsets",
		filepath.Base(*output), *size, twiddleBytes, scatterBytes,
	)
}

func writeHeader(out *bufio.Writer, size int) {
	_, _ = fmt.Fprintf(out, "// Code generated by \"go generate\"; DO NOT EDIT.\n")
	_, _ = fmt.Fprintf(out, "// Source: server/internal/calc/gen, regenerate with `go generate ./server/internal/calc/...`.\n")
	_, _ = fmt.Fprintf(out, "//\n")
	_, _ = fmt.Fprintf(out, "// Lookup tables for the %d point fast Fourier transform, shared by every\n", size)
	_, _ = fmt.Fprintf(out, "// assembly implementation in the package.\n")
	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "#include \"textflag.h\"\n")
}

// writeTwiddles emits the roots of unity for every radix-2 stage the assembly
// runs, which is every stage from eight points wide up to the full transform.
// The first two stages are folded into the radix-4 pass that also does the bit
// reversal, and their twiddle factors are all either 1 or -i, so they do not
// need a table at all.
//
// The assembly runs these as radix-4 passes, each one covering two radix-2
// stages at once.
//
// A pass with parameter h needs three twiddle factors per butterfly:
//
//	w1 = W(2h)^j      for the first of the two folded stages
//	w2 = W(4h)^j      for the lower pair of the second stage
//	w3 = W(4h)^(j+h)  for the upper pair of the second stage
//
// Only the first two are stored. The third is always -i times the second,
// which the assembly derives with a swap of the real and imaginary halves plus
// a sign flip.
func writeTwiddles(out *bufio.Writer, size int) int {
	symbol := fmt.Sprintf("·fourierTwiddles%d", size)

	writeHeader(out, size)
	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "// %s holds the complex roots of unity for the radix-4\n", symbol[len("·"):])
	_, _ = fmt.Fprintf(out, "// passes, stored as interleaved (real, imaginary) float64 pairs exactly the way\n")
	_, _ = fmt.Fprintf(out, "// Go lays out a complex128. Each pass contributes h copies of W(2h)^j followed\n")
	_, _ = fmt.Fprintf(out, "// by h copies of W(4h)^j, and the passes are packed smallest first so the\n")
	_, _ = fmt.Fprintf(out, "// assembly can just walk a cursor forward by 2h entries after each one.\n")

	offset := 0
	emit := func(value float64) {
		_, _ = fmt.Fprintf(out, "DATA %s+%d(SB)/8, $0x%016x\n", symbol, offset, math.Float64bits(value))
		offset += 8
	}

	for h := 4; h*4 <= size; h *= 4 {
		_, _ = fmt.Fprintf(out, "\n")
		_, _ = fmt.Fprintf(
			out,
			"// Radix-4 pass h=%d, covering the %d and %d point stages.\n",
			h, 2*h, 4*h,
		)
		// math.Sincos behaves slightly differently on different CPUs, this is
		// expected to be run on an amd64 CPU but running it on an arm64 CPU might
		// yield slightly different results for the generated table. Its not wrong,
		// its just floating point bullshit
		_, _ = fmt.Fprintf(out, "// First %d entries are W(%d)^j, the twiddle for the folded first stage.\n", h, 2*h)
		for j := 0; j < h; j++ {
			sin, cos := math.Sincos(-2 * math.Pi * float64(j) / float64(2*h))
			emit(cos)
			emit(sin)
		}
		_, _ = fmt.Fprintf(out, "// Next %d entries are W(%d)^j for the folded second stage. Its partner\n", h, 4*h)
		_, _ = fmt.Fprintf(out, "// W(%d)^(j+%d) is -i times this and is derived in registers.\n", 4*h, h)
		for j := 0; j < h; j++ {
			sin, cos := math.Sincos(-2 * math.Pi * float64(j) / float64(4*h))
			emit(cos)
			emit(sin)
		}
	}
	_, _ = fmt.Fprintf(out, "\nGLOBL %s(SB), (RODATA+NOPTR), $%d\n", symbol, offset)

	return offset
}

// writeScatter emits where each group of four outputs from the first pass has
// to land.
//
// The first pass reads four source points that are a quarter of the transform
// apart, combines them into four finished outputs, and those four outputs are
// always contiguous in the bit reversed buffer. Which group of four they belong
// to is the bit reversal of the source index, so all the permutation costs at
// runtime is one 32 bit load per group.
func writeScatter(out *bufio.Writer, size int) int {
	symbol := fmt.Sprintf("·fourierScatter%d", size)
	quarter := size / 4

	bits := 0
	for 1<<bits < quarter {
		bits++
	}

	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "// %s is the bit reversal permutation, already multiplied\n", symbol[len("·"):])
	_, _ = fmt.Fprintf(out, "// out into byte offsets. Entry q is 64 * reverse%d(q), the byte offset of the\n", bits)
	_, _ = fmt.Fprintf(out, "// group of four complex128 values that source group q produces. Storing offsets\n")
	_, _ = fmt.Fprintf(out, "// rather than indices keeps the first pass down to a load and an indexed store.\n")

	offset := 0
	for q := range quarter {
		reversed := 0
		for bit := 0; bit < bits; bit++ {
			if q&(1<<bit) != 0 {
				reversed |= 1 << (bits - 1 - bit)
			}
		}
		// Four complex128 values is 64 bytes, so the group index scales straight
		// into a byte offset.
		_, _ = fmt.Fprintf(out, "DATA %s+%d(SB)/4, $%d\n", symbol, offset, reversed*64)
		offset += 4
	}
	_, _ = fmt.Fprintf(out, "\nGLOBL %s(SB), (RODATA+NOPTR), $%d\n", symbol, offset)

	return offset
}

// Command gen writes the lookup tables that the fixed size assembly
// implementation of the fast Fourier transform depends on.
//
// Everything the transform needs that only depends on the transform size gets
// worked out here and baked into a .s file as read only data. At runtime the
// assembly just walks these tables, so there is not a single sine, cosine or
// bit reversal being computed while the server is actually running.
//
// Two tables come out of this:
//
//   - fourierTwiddles<size>, the complex roots of unity for every radix-2 stage
//     from the eight point stage on up. They are laid out end to end in the
//     order the stages consume them so the inner loop only ever reads forward.
//
//   - fourierScatter<size>, the byte offset each group of four outputs from the
//     first pass belongs at. This is the bit reversal permutation, converted
//     ahead of time into the exact offsets the store instructions want.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"path/filepath"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	size := flag.Int("size", 4096, "number of points the transform is built for, must be a power of two")
	output := flag.String("output", "fourier_twiddles_amd64.s", "path of the assembly file to write")
	flag.Parse()

	if *size < 8 || *size&(*size-1) != 0 {
		log.Fatalf("size must be a power of two that is at least 8, got %d", *size)
	}

	file, err := os.Create(*output)
	if err != nil {
		log.Fatalf("could not create %s: %v", *output, err)
	}
	defer file.Close()

	buffer := bufio.NewWriterSize(file, 1<<20)
	twiddleBytes := writeTwiddles(buffer, *size)
	scatterBytes := writeScatter(buffer, *size)
	if err := buffer.Flush(); err != nil {
		log.Fatalf("could not write %s: %v", *output, err)
	}

	log.Printf(
		"wrote %s for %d points, %d bytes of twiddle factors and %d bytes of scatter offsets",
		filepath.Base(*output), *size, twiddleBytes, scatterBytes,
	)
}

func writeHeader(out *bufio.Writer, size int) {
	_, _ = fmt.Fprintf(out, "// Code generated by \"go generate\"; DO NOT EDIT.\n")
	_, _ = fmt.Fprintf(out, "// Source: server/internal/calc/gen, regenerate with `go generate ./server/internal/calc/...`.\n")
	_, _ = fmt.Fprintf(out, "//\n")
	_, _ = fmt.Fprintf(out, "// Lookup tables for the %d point AVX512 fast Fourier transform. Every value\n", size)
	_, _ = fmt.Fprintf(out, "// in here only depends on the transform size, so it is all worked out at build\n")
	_, _ = fmt.Fprintf(out, "// time and none of it costs anything while the server is running.\n")
	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "#include \"textflag.h\"\n")
}

// writeTwiddles emits the roots of unity for every radix-2 stage the assembly
// runs, which is every stage from eight points wide up to the full transform.
// The first two stages are folded into the radix-4 pass that also does the bit
// reversal, and their twiddle factors are all either 1 or -i, so they do not
// need a table at all.
//
// A stage whose half width is h reads h entries starting at index h-4. That
// falls out of the fact that the halves double every stage: 4 + 8 + ... + h/2
// is exactly h-4. The assembly relies on it so it never needs a table of table
// offsets, it just subtracts a constant from the byte width of the stage.
func writeTwiddles(out *bufio.Writer, size int) int {
	symbol := fmt.Sprintf("·fourierTwiddles%d", size)

	writeHeader(out, size)
	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "// %s holds the complex roots of unity for the radix-2\n", symbol[len("·"):])
	_, _ = fmt.Fprintf(out, "// stages, stored as interleaved (real, imaginary) float64 pairs exactly the way\n")
	_, _ = fmt.Fprintf(out, "// Go lays out a complex128. A stage whose half width is h reads h entries\n")
	_, _ = fmt.Fprintf(out, "// beginning at entry h-4, which is why the table is packed smallest stage first.\n")

	offset := 0
	for half := 4; half <= size/2; half <<= 1 {
		length := half * 2
		_, _ = fmt.Fprintf(out, "\n")
		_, _ = fmt.Fprintf(
			out,
			"// Stage %d, %d twiddle factors of the form e^(-2*pi*i*j/%d) for j in [0, %d).\n",
			length, half, length, half,
		)
		for j := 0; j < half; j++ {
			sin, cos := math.Sincos(-2 * math.Pi * float64(j) / float64(length))
			_, _ = fmt.Fprintf(out, "DATA %s+%d(SB)/8, $0x%016x\n", symbol, offset, math.Float64bits(cos))
			offset += 8
			_, _ = fmt.Fprintf(out, "DATA %s+%d(SB)/8, $0x%016x\n", symbol, offset, math.Float64bits(sin))
			offset += 8
		}
	}
	_, _ = fmt.Fprintf(out, "\nGLOBL %s(SB), (RODATA+NOPTR), $%d\n", symbol, offset)

	return offset
}

// writeScatter emits where each group of four outputs from the first pass has
// to land.
//
// The first pass reads four source points that are a quarter of the transform
// apart, combines them into four finished outputs, and those four outputs are
// always contiguous in the bit reversed buffer. Which group of four they belong
// to is the bit reversal of the source index, so all the permutation costs at
// runtime is one 32 bit load per group.
func writeScatter(out *bufio.Writer, size int) int {
	symbol := fmt.Sprintf("·fourierScatter%d", size)
	quarter := size / 4

	bits := 0
	for 1<<bits < quarter {
		bits++
	}

	_, _ = fmt.Fprintf(out, "\n")
	_, _ = fmt.Fprintf(out, "// %s is the bit reversal permutation, already multiplied\n", symbol[len("·"):])
	_, _ = fmt.Fprintf(out, "// out into byte offsets. Entry q is 64 * reverse%d(q), the byte offset of the\n", bits)
	_, _ = fmt.Fprintf(out, "// group of four complex128 values that source group q produces. Storing offsets\n")
	_, _ = fmt.Fprintf(out, "// rather than indices keeps the first pass down to a load and an indexed store.\n")

	offset := 0
	for q := range quarter {
		reversed := 0
		for bit := 0; bit < bits; bit++ {
			if q&(1<<bit) != 0 {
				reversed |= 1 << (bits - 1 - bit)
			}
		}
		// Four complex128 values is 64 bytes, so the group index scales straight
		// into a byte offset.
		_, _ = fmt.Fprintf(out, "DATA %s+%d(SB)/4, $%d\n", symbol, offset, reversed*64)
		offset += 4
	}
	_, _ = fmt.Fprintf(out, "\nGLOBL %s(SB), (RODATA+NOPTR), $%d\n", symbol, offset)

	return offset
}
